/// One named value carried by a Strum `props` attribute.
#[derive(Clone)]
struct StrumProperty {
    /// Property name.
    name: String,
    /// Property value.
    _value: String,
}

/// Strum derive macros relevant to the framework-aware lint layer.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum StrumDerive {
    /// Borrowed string views generated by `AsRefStr`.
    AsRefStr,
    /// Formatting generated by `Display`.
    Display,
    /// Variant cardinality generated by `EnumCount`.
    EnumCount,
    /// Companion discriminant types generated by `EnumDiscriminants`.
    EnumDiscriminants,
    /// Variant iteration generated by `EnumIter`.
    EnumIter,
    /// Runtime messages generated by `EnumMessage`.
    EnumMessage,
    /// Static metadata generated by `EnumProperty`.
    EnumProperty,
    /// String parsing generated by `EnumString`.
    EnumString,
    /// Discriminant conversion generated by `FromRepr`.
    FromRepr,
    /// Owned-to-static-string conversion generated by `IntoStaticStr`.
    IntoStaticStr,
    /// Ordered variant arrays generated by `VariantArray`.
    VariantArray,
    /// Variant spelling tables generated by `VariantNames`.
    VariantNames,
}

impl StrumDerive {
    /// Resolves the Strum behavior generated by a derive macro name.
    fn from_macro_name(name: &str) -> Option<Self> {
        match name {
            "AsRefStr" => Some(Self::AsRefStr),
            "Display" => Some(Self::Display),
            "EnumCount" => Some(Self::EnumCount),
            "EnumDiscriminants" => Some(Self::EnumDiscriminants),
            "EnumIter" => Some(Self::EnumIter),
            "EnumMessage" => Some(Self::EnumMessage),
            "EnumProperty" => Some(Self::EnumProperty),
            "EnumString" => Some(Self::EnumString),
            "FromRepr" => Some(Self::FromRepr),
            "IntoStaticStr" => Some(Self::IntoStaticStr),
            "VariantArray" => Some(Self::VariantArray),
            "VariantNames" | "EnumVariantNames" => Some(Self::VariantNames),
            _ => None,
        }
    }
}

