// -----------------------------------------------------------------------------
// CaseStyle: Strum case-conversion vocabulary
// -----------------------------------------------------------------------------

/// Case conversions accepted by Strum's `serialize_all` attribute.
#[derive(Clone, Copy)]
enum CaseStyle {
    /// Lower camel case, such as `variantName`.
    Camel,
    /// Lower kebab case, such as `variant-name`.
    Kebab,
    /// Lowercase with no word separator.
    Lower,
    /// Lower snake case under Strum's `mixed_case` spelling.
    Mixed,
    /// Upper camel case, such as `VariantName`.
    Pascal,
    /// Upper kebab case, such as `VARIANT-NAME`.
    ScreamingKebab,
    /// Upper snake case, such as `VARIANT_NAME`.
    ScreamingSnake,
    /// Lower snake case, such as `variant_name`.
    Snake,
    /// Space-separated title case, such as `Variant Name`.
    Title,
    /// Hyphenated title case, such as `Variant-Name`.
    Train,
    /// Uppercase with no word separator.
    Upper,
}

impl CaseStyle {
    /// Parses Strum's authored case-conversion vocabulary.
    fn from_name(value: &str) -> Option<Self> {
        match value {
            "camelCase" => Some(Self::Camel),
            "kebab-case" => Some(Self::Kebab),
            "lowercase" => Some(Self::Lower),
            "mixed_case" => Some(Self::Mixed),
            "PascalCase" => Some(Self::Pascal),
            "SCREAMING-KEBAB-CASE" => Some(Self::ScreamingKebab),
            "SCREAMING_SNAKE_CASE" => Some(Self::ScreamingSnake),
            "snake_case" => Some(Self::Snake),
            "title_case" => Some(Self::Title),
            "Train-Case" => Some(Self::Train),
            "UPPERCASE" => Some(Self::Upper),
            _ => None,
        }
    }

    /// Applies the selected conversion to an authored variant name.
    fn apply(value: &str, style: Option<Self>) -> String {
        match style {
            Some(Self::Camel) => value.to_lower_camel_case(),
            Some(Self::Kebab) => value.to_kebab_case(),
            Some(Self::Lower) => value.to_lowercase(),
            Some(Self::Mixed | Self::Snake) => value.to_snake_case(),
            Some(Self::Pascal) => value.to_upper_camel_case(),
            Some(Self::ScreamingKebab) => value.to_shouty_kebab_case(),
            Some(Self::ScreamingSnake) => value.to_shouty_snake_case(),
            Some(Self::Title) => value.to_title_case(),
            Some(Self::Train) => value.to_train_case(),
            Some(Self::Upper) => value.to_uppercase(),
            None => value.to_owned(),
        }
    }
}

// -----------------------------------------------------------------------------
// StrumAttributeValue: Nested attribute value parsing
// -----------------------------------------------------------------------------

/// Reads typed values from nested Strum attributes.
struct StrumAttributeValue;

impl StrumAttributeValue {
    /// Reads a required string value.
    fn string(meta: &ParseNestedMeta<'_>) -> syn::Result<String> {
        Ok(meta.value()?.parse::<LitStr>()?.value())
    }

    /// Reads a boolean flag, treating a bare flag as enabled.
    fn boolean(meta: &ParseNestedMeta<'_>) -> syn::Result<bool> {
        if meta.input.peek(Token![=]) {
            Ok(meta.value()?.parse::<LitBool>()?.value)
        } else {
            Ok(true)
        }
    }
}

// -----------------------------------------------------------------------------
// TypeAttributes: Type-level Strum policy
// -----------------------------------------------------------------------------

/// Parsed type-level attributes that transform every generated variant spelling.
#[derive(Clone, Default)]
struct TypeAttributes {
    /// Optional case conversion applied before per-variant overrides.
    from_name: Option<CaseStyle>,
    /// Default ASCII-insensitive parsing policy inherited by variants.
    is_ascii_case_insensitive: bool,
    /// Text prepended to generated spellings for every variant.
    prefix: Option<String>,
    /// Text appended to generated spellings for every variant.
    suffix: Option<String>,
}

impl TypeAttributes {
    /// Parses type-wide naming and parser policy from Strum attributes.
    fn from_attrs(attributes: &[syn::Attribute]) -> Self {
        let mut output = Self::default();
        for attribute in attributes {
            if !attribute.path().is_ident("strum") {
                continue;
            }
            let parsing = attribute.parse_nested_meta(|meta| {
                if meta.path.is_ident("serialize_all") {
                    output.from_name = CaseStyle::from_name(&StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("ascii_case_insensitive") {
                    output.is_ascii_case_insensitive = StrumAttributeValue::boolean(&meta)?;
                } else if meta.path.is_ident("prefix") {
                    output.prefix = Some(StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("suffix") {
                    output.suffix = Some(StrumAttributeValue::string(&meta)?);
                }
                Ok(())
            });

            // Malformed Strum metadata cannot contribute a reliable type-wide policy.
            if parsing.is_err() {
                return output;
            }
        }
        output
    }
}

// -----------------------------------------------------------------------------
// VariantAttributes: Variant-level Strum policy
// -----------------------------------------------------------------------------

/// Parsed per-variant overrides for generated parsing, display, and metadata.
#[derive(Clone, Default)]
struct VariantAttributes {
    /// Explicit aliases accepted by generated parsers.
    serializations: Vec<String>,
    /// Explicit spelling selected for generated output.
    to_string: Option<String>,
    /// Whether generated Strum APIs exclude this variant.
    is_disabled: bool,
    /// Whether this variant captures parser input unmatched by explicit aliases.
    is_default_capture: bool,
    /// Per-variant override for ASCII-insensitive parsing.
    is_ascii_case_insensitive: Option<bool>,
    /// Authored message participating in the contract.
    message: Option<String>,
    /// Longer runtime message authored for this variant.
    detailed_message: Option<String>,
    /// Static metadata entries authored for this variant.
    properties: Vec<StrumProperty>,
    /// Whether parsing uses authored payload constructors instead of `Default`.
    has_explicit_string_payload: bool,
}

impl VariantAttributes {
    /// Parses per-variant naming, message, and metadata overrides.
    fn from_attrs(attributes: &[syn::Attribute]) -> Self {
        let mut output = Self::default();
        for attribute in attributes {
            if !attribute.path().is_ident("strum") {
                continue;
            }
            let parsing = attribute.parse_nested_meta(|meta| {
                if meta.path.is_ident("serialize") {
                    output
                        .serializations
                        .push(StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("to_string") {
                    output.to_string = Some(StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("disabled") {
                    output.is_disabled = true;
                } else if meta.path.is_ident("default") {
                    output.is_default_capture = true;
                } else if meta.path.is_ident("default_with") {
                    let _constructor = StrumAttributeValue::string(&meta)?;
                    output.has_explicit_string_payload = true;
                } else if meta.path.is_ident("ascii_case_insensitive") {
                    output.is_ascii_case_insensitive = Some(StrumAttributeValue::boolean(&meta)?);
                } else if meta.path.is_ident("message") {
                    output.message = Some(StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("detailed_message") {
                    output.detailed_message = Some(StrumAttributeValue::string(&meta)?);
                } else if meta.path.is_ident("props") {
                    meta.parse_nested_meta(|property| {
                        // Unnamed properties cannot provide a stable metadata key.
                        let Some(name) = property.path.get_ident() else {
                            return Ok(());
                        };
                        output.properties.push(StrumProperty {
                            name: name.to_string(),
                            _value: StrumAttributeValue::string(&property)?,
                        });
                        Ok(())
                    })?;
                }
                Ok(())
            });

            // Malformed Strum metadata cannot contribute reliable variant policy.
            if parsing.is_err() {
                return output;
            }
        }
        output
    }
}

// -----------------------------------------------------------------------------
// SourceAttributes: Parsed authored Strum policy
// -----------------------------------------------------------------------------

/// Complete authored Strum policy recovered from source-level attributes.
struct SourceAttributes {
    /// Resolved type involved in the contract.
    ty: TypeAttributes,
    /// Variants participating in the analyzed contract.
    variants: HashMap<String, VariantAttributes>,
    /// Authored declaration or expression range used as the diagnostic anchor.
    span: Span,
}

impl SourceAttributes {
    /// Recovers this contract from one authored declaration.
    fn from_item(cx: &LateContext<'_>, item: &Item<'_>) -> Option<Self> {
        let EnumSource { source, span } = EnumSource::for_item(cx, item)?;
        let parsed = match syn::parse_str::<syn::ItemEnum>(&source) {
            Ok(parsed) => parsed,
            // Source unavailable from the compiler cannot be parsed for outer attributes.
            Err(_error) => return None,
        };

        Some(Self {
            ty: TypeAttributes::from_attrs(&parsed.attrs),
            variants: parsed
                .variants
                .into_iter()
                .map(|variant| {
                    let mut attributes = VariantAttributes::from_attrs(&variant.attrs);
                    if let syn::Fields::Named(fields) = &variant.fields {
                        attributes.has_explicit_string_payload = fields.named.iter().all(|field| {
                            field.attrs.iter().any(|attribute| {
                                // Non-Strum attributes cannot define default payload construction.
                                if !attribute.path().is_ident("strum") {
                                    return false;
                                }
                                let mut found = false;
                                let parsing = attribute.parse_nested_meta(|meta| {
                                    if meta.path.is_ident("default_with") {
                                        let _constructor = StrumAttributeValue::string(&meta)?;
                                        found = true;
                                    }
                                    Ok(())
                                });
                                parsing.is_ok() && found
                            })
                        });
                    }
                    (variant.ident.to_string(), attributes)
                })
                .collect(),
            span,
        })
    }
}

// -----------------------------------------------------------------------------
// EnumSource: Attribute-inclusive enum source recovery
// -----------------------------------------------------------------------------

/// Authored enum source together with the span that includes its attributes.
struct EnumSource {
    /// Source text parsed for Strum attributes.
    source: String,
    /// Span corresponding to the recovered source.
    span: Span,
}

impl EnumSource {
    /// Recovers an enum declaration together with its outer attributes.
    fn for_item(cx: &LateContext<'_>, item: &Item<'_>) -> Option<Self> {
        let source_map = cx.tcx.sess.source_map();
        let item_source = match source_map.span_to_snippet(item.span) {
            Ok(source) => source,
            // Source unavailable from the compiler cannot be parsed for outer attributes.
            Err(_error) => return None,
        };
        let location = source_map.lookup_char_pos(item.span.lo());
        let file_source = location.file.src.as_deref()?;

        // Offsets outside the source file cannot delimit the attributed enum source.
        let offset = match usize::try_from(item.span.lo().0.checked_sub(location.file.start_pos.0)?)
        {
            Ok(offset) => offset,
            // Offsets outside the source file cannot delimit the attributed enum source.
            Err(_error) => return None,
        };
        let bytes = file_source.as_bytes();
        let mut start = offset;

        loop {
            while start > 0 && bytes[start - 1].is_ascii_whitespace() {
                start -= 1;
            }
            if start == 0 || bytes[start - 1] != b']' {
                break;
            }
            let mut cursor = start - 1;
            let mut depth = 1_u32;
            while cursor > 0 && depth > 0 {
                cursor -= 1;
                match bytes[cursor] {
                    b']' => depth += 1,
                    b'[' => depth -= 1,
                    _ => {}
                }
            }
            if depth != 0 || cursor == 0 || bytes[cursor - 1] != b'#' {
                break;
            }
            start = cursor - 1;
        }

        // Source positions that exceed rustc's byte range cannot form a span.
        let source_offset = match u32::try_from(start) {
            Ok(offset) => offset,
            // Source positions that exceed rustc's byte range cannot form a span.
            Err(_error) => return None,
        };
        let source_lo = rustc_span::BytePos(location.file.start_pos.0 + source_offset);

        Some(Self {
            source: format!("{}{}", &file_source[start..offset], item_source),
            span: item.span.with_lo(source_lo),
        })
    }
}

// -----------------------------------------------------------------------------
// StrumAssociatedItem: Generated associated-contract recognition
// -----------------------------------------------------------------------------

/// Trait and item names that identify one Strum associated contract.
pub struct StrumAssociatedItem<'name> {
    /// Strum trait owning the associated item.
    pub(crate) trait_name: &'name str,
    /// Associated function or constant name.
    pub(crate) item_name: &'name str,
}

impl StrumAssociatedItem<'_> {
    /// Resolves the enum type in a `Type::ITEM` path owned by this Strum contract.
    pub(crate) fn enum_definition(
        &self,
        cx: &LateContext<'_>,
        expression: &Expr<'_>,
    ) -> Option<LocalDefId> {
        // Only paths can refer to a generated associated Strum item.
        let ExprKind::Path(path) = expression.kind else {
            return None;
        };
        let definition = cx.qpath_res(&path, expression.hir_id).opt_def_id()?;

        // Only associated functions and constants can be the queried Strum contract.
        if !matches!(
            cx.tcx.def_kind(definition),
            DefKind::AssocFn | DefKind::AssocConst { .. }
        ) {
            return None;
        }

        let contract_definition = cx
            .tcx
            .associated_item(definition)
            .trait_item_def_id()
            .unwrap_or(definition);

        // Other associated items do not match the requested Strum contract member.
        if cx.tcx.item_name(contract_definition).as_str() != self.item_name {
            return None;
        }
        let path_name = cx.tcx.def_path_str(contract_definition);

        // Items outside the expected Strum trait are unrelated associated members.
        if !path_name.contains("strum") || !path_name.contains(self.trait_name) {
            return None;
        }

        // Only type-relative paths expose the enum receiver type.
        let QPath::TypeRelative(ty, _) = path else {
            return None;
        };

        cx.typeck_results()
            .node_type(ty.hir_id)
            .ty_adt_def()?
            .did()
            .as_local()
    }
}
