/// Authored Strum metadata inspection for enum variants.
pub struct VariantMetadata;

impl VariantMetadata {
    /// Returns whether one variant is excluded by canonical `#[strum(disabled)]` metadata.
    pub fn is_strum_disabled(cx: &LateContext<'_>, hir_id: rustc_hir::HirId) -> bool {
        let span = cx.tcx.hir_span(hir_id);
        let source_map = cx.tcx.sess.source_map();
        let location = source_map.lookup_char_pos(span.lo());

        // Attribute scanning requires the compiler to retain this file's source text.
        let Some(file_source) = location.file.src.as_deref() else {
            return false;
        };

        // A span outside its source file cannot identify the preceding attributes.
        let Some(raw_offset) = span.lo().0.checked_sub(location.file.start_pos.0) else {
            return false;
        };

        // The byte offset must fit the source slice before it can be indexed.
        let Ok(offset) = usize::try_from(raw_offset) else {
            return false;
        };
        let bytes = file_source.as_bytes();
        let mut start = offset;
        loop {
            while start > 0 && bytes[start - 1].is_ascii_whitespace() {
                start -= 1;
            }
            if start == 0 || bytes[start - 1] != b']' {
                break;
            }
            let mut cursor = start - 1;
            let mut depth = 1_u32;
            while cursor > 0 && depth > 0 {
                cursor -= 1;
                match bytes[cursor] {
                    b']' => depth += 1,
                    b'[' => depth -= 1,
                    _ => {}
                }
            }
            if depth != 0 || cursor == 0 || bytes[cursor - 1] != b'#' {
                break;
            }
            start = cursor - 1;
        }

        file_source[start..offset].split("#[").any(|attribute| {
            attribute.trim_start().starts_with("strum")
                && attribute
                    .split(|character: char| !(character.is_alphanumeric() || character == '_'))
                    .any(|component| component == "disabled")
        })
    }
}

/// Resolves a positive integer literal pattern.
#[cfg(feature = "strum")]
fn integer_pattern(pattern: &Pat<'_>) -> Option<u128> {
    // Only expression patterns can encode a literal discriminant.
    let PatKind::Expr(expression) = pattern.kind else {
        return None;
    };

    // Negative and non-literal patterns do not represent supported discriminants.
    let PatExprKind::Lit {
        lit: literal,
        negated: false,
    } = expression.kind
    else {
        return None;
    };

    // Repr conversion matching requires an integer literal specifically.
    let rustc_ast::LitKind::Int(value, _) = literal.node else {
        return None;
    };
    Some(value.get())
}

/// Resolves a path or constructor resolution to its local variant definition.
fn variant_from_res(cx: &LateContext<'_>, resolution: Res) -> Option<LocalDefId> {
    match resolution {
        Res::Def(DefKind::Variant, variant) => variant.as_local(),
        Res::Def(DefKind::Ctor(CtorOf::Variant, _), constructor) => {
            cx.tcx.opt_local_parent(constructor.as_local()?)
        }
        _ => None,
    }
}

/// Resolves a variant pattern whose payload is entirely ignored.
fn ignored_variant_pattern(cx: &LateContext<'_>, pattern: &Pat<'_>) -> Option<LocalDefId> {
    let resolution = match pattern.kind {
        PatKind::Expr(expression) => {
            // A payload-free variant must be written as a direct path.
            let PatExprKind::Path(path) = expression.kind else {
                return None;
            };
            cx.qpath_res(&path, expression.hir_id)
        }
        PatKind::TupleStruct(path, fields, _)
            if fields
                .iter()
                .all(|field| matches!(field.kind, PatKind::Wild)) =>
        {
            cx.qpath_res(&path, pattern.hir_id)
        }
        PatKind::Struct(path, fields, _)
            if fields
                .iter()
                .all(|field| matches!(field.pat.kind, PatKind::Wild)) =>
        {
            cx.qpath_res(&path, pattern.hir_id)
        }

        // Any other pattern can observe or bind payload data.
        _ => return None,
    };

    variant_from_res(cx, resolution)
}

/// Resolves one plain binding pattern.
const fn binding_id(pattern: &Pat<'_>) -> Option<rustc_hir::HirId> {
    // Generated accessors require an unmodified binding for each payload field.
    let PatKind::Binding(_, binding, _, None) = pattern.kind else {
        return None;
    };
    Some(binding)
}

/// Tuple-variant identity and its ordered field bindings.
#[cfg(feature = "strum")]
struct BoundTupleVariant {
    /// Matched local enum variant.
    variant: LocalDefId,
    /// Ordered bindings for the variant payload.
    bindings: Vec<rustc_hir::HirId>,
}

#[cfg(feature = "strum")]
impl BoundTupleVariant {
    /// Resolves a tuple-variant pattern and its ordered field bindings.
    fn analyze(cx: &LateContext<'_>, pattern: &Pat<'_>) -> Option<Self> {
        // Only tuple-variant patterns can establish ordered payload bindings.
        let PatKind::TupleStruct(path, fields, rest) = pattern.kind else {
            return None;
        };

        // A rest pattern omits fields, so it cannot prove an exact accessor.
        if rest.as_opt_usize().is_some() {
            return None;
        }

        let bindings = fields
            .iter()
            .map(|field| binding_id(field))
            .collect::<Option<Vec<_>>>()?;

        Some(Self {
            variant: variant_from_res(cx, cx.qpath_res(&path, pattern.hir_id))?,
            bindings,
        })
    }
}

/// Returns whether a constructor is the named variant of standard `Option`.
#[cfg(feature = "strum")]
fn is_option_variant(cx: &LateContext<'_>, constructor: DefId, name: &str) -> bool {
    let variant = cx.tcx.parent(constructor);
    cx.tcx.item_name(variant).as_str() == name
        && cx
            .tcx
            .is_diagnostic_item(sym::Option, cx.tcx.parent(variant))
}

/// Returns the payload of an exact standard `Option` return type.
#[cfg(feature = "strum")]
fn option_output<'tcx>(cx: &LateContext<'tcx>, definition: LocalDefId) -> Option<ty::Ty<'tcx>> {
    let output = cx
        .tcx
        .fn_sig(definition)
        .instantiate_identity()
        .skip_binder()
        .output();

    // Accessor recognition is meaningful only for an exact `Option` result.
    let ty::Adt(option, arguments) = output.kind() else {
        return None;
    };
    cx.tcx
        .is_diagnostic_item(sym::Option, option.did())
        .then(|| arguments.type_at(0))
}

/// Verifies the shared receiver contract generated by `EnumIs`.
fn has_shared_receiver(cx: &LateContext<'_>, definition: LocalDefId, enum_def: LocalDefId) -> bool {
    let signature = cx
        .tcx
        .fn_sig(definition)
        .instantiate_identity()
        .skip_binder();

    // Predicate methods must have a receiver to be generated from the enum.
    let Some(receiver) = signature.inputs().first() else {
        return false;
    };
    matches!(
        receiver.kind(),
        ty::Ref(_, inner, rustc_hir::Mutability::Not)
            if inner.ty_adt_def().is_some_and(|definition| definition.did().as_local() == Some(enum_def))
    ) && signature.output().is_bool()
}

/// Finds the local enum targeted by an inherent implementation item.
fn enclosing_inherent_enum(cx: &LateContext<'_>, hir_id: rustc_hir::HirId) -> Option<LocalDefId> {
    cx.tcx.hir_parent_iter(hir_id).find_map(|(_, node)| {
        // Only item ancestors can contain an inherent implementation.
        let Node::Item(item) = node else {
            return None;
        };

        // The candidate must live in an implementation item.
        let rustc_hir::ItemKind::Impl(implementation) = item.kind else {
            return None;
        };

        // Trait implementations do not establish inherent generated methods.
        if implementation.of_trait.is_some() {
            return None;
        }
        cx.tcx
            .type_of(item.owner_id)
            .instantiate_identity()
            .ty_adt_def()?
            .did()
            .as_local()
    })
}

/// Returns the enum owning one local variant.
fn owning_enum(cx: &LateContext<'_>, variant: LocalDefId) -> Option<LocalDefId> {
    cx.tcx.opt_local_parent(variant)
}

/// Rejects enums whose variant attributes may disable or rename generated methods.
fn has_enum_strum_variant_attributes(cx: &LateContext<'_>, enum_def: LocalDefId) -> bool {
    // Unknown HIR structure may hide attributes that alter generated coverage.
    let Node::Item(item) = cx.tcx.hir_node_by_def_id(enum_def) else {
        return true;
    };

    // Only enum definitions expose the variant metadata being checked.
    let rustc_hir::ItemKind::Enum(_, _, definition) = item.kind else {
        return true;
    };
    let strum = Symbol::intern("strum");
    definition.variants.iter().any(|variant| {
        cx.tcx
            .hir_attrs(variant.hir_id)
            .iter()
            .any(|attribute| attribute.has_name(strum))
    })
}

/// Returns whether Strum excludes any variant from generated enum APIs.
#[cfg(feature = "strum")]
fn has_enum_strum_disabled_variant(cx: &LateContext<'_>, enum_def: LocalDefId) -> bool {
    // Unknown HIR structure may hide disabled variants.
    let Node::Item(item) = cx.tcx.hir_node_by_def_id(enum_def) else {
        return true;
    };

    // Only enum definitions expose the disabled-variant metadata.
    let rustc_hir::ItemKind::Enum(_, _, definition) = item.kind else {
        return true;
    };
    definition
        .variants
        .iter()
        .any(|variant| VariantMetadata::is_strum_disabled(cx, variant.hir_id))
}

/// Returns every variant when Strum attributes cannot change generated coverage.
fn eligible_variants(
    cx: &LateContext<'_>,
    enum_def: LocalDefId,
    provider: Option<PredicateProvider>,
) -> Option<Vec<LocalDefId>> {
    // Strum metadata can change coverage unless a concrete provider was selected.
    if provider.is_none() && has_enum_strum_variant_attributes(cx, enum_def) {
        return None;
    }

    // The candidate must resolve to a local enum item.
    let Node::Item(item) = cx.tcx.hir_node_by_def_id(enum_def) else {
        return None;
    };

    // Variant enumeration requires the item to remain an enum.
    let rustc_hir::ItemKind::Enum(_, _, definition) = item.kind else {
        return None;
    };
    Some(
        definition
            .variants
            .iter()
            .filter(|variant| {
                provider != Some(PredicateProvider::StrumEnumIs)
                    || !VariantMetadata::is_strum_disabled(cx, variant.hir_id)
            })
            .map(|variant| variant.def_id)
            .collect(),
    )
}

/// Returns every tuple variant when Strum attributes cannot change generated coverage.
#[cfg(feature = "strum")]
fn eligible_tuple_variants(cx: &LateContext<'_>, enum_def: LocalDefId) -> Option<Vec<LocalDefId>> {
    let variants = eligible_variants(cx, enum_def, Some(PredicateProvider::StrumEnumIs))?;
    let definition = cx.tcx.adt_def(enum_def.to_def_id());

    Some(
        variants
            .into_iter()
            .filter(|variant| {
                definition
                    .variants()
                    .iter()
                    .find(|candidate| candidate.def_id.as_local() == Some(*variant))
                    .is_some_and(|candidate| {
                        !candidate.fields.is_empty() && candidate.ctor_kind() == Some(CtorKind::Fn)
                    })
            })
            .collect(),
    )
}

/// Removes blocks and compiler drop-temporary wrappers without changing semantics.
const fn peel_transparent<'hir>(mut expression: &'hir Expr<'hir>) -> &'hir Expr<'hir> {
    loop {
        expression = match expression.kind {
            ExprKind::Block(block, None) if block.stmts.is_empty() => {
                // An empty block without a tail expression cannot be peeled further.
                let Some(inner) = block.expr else {
                    return expression;
                };
                inner
            }
            ExprKind::DropTemps(inner) => inner,

            // Any other expression wrapper is semantically significant.
            _ => return expression,
        };
    }
}

/// Resolves a literal boolean after transparent blocks.
const fn is_bool_literal(expression: &Expr<'_>) -> Option<bool> {
    // Only literal expressions can prove a boolean match arm's result.
    let ExprKind::Lit(literal) = peel_transparent(expression).kind else {
        return None;
    };

    // Non-boolean literals do not identify a positive or negative arm.
    let rustc_ast::LitKind::Bool(value) = literal.node else {
        return None;
    };
    Some(value)
}

/// Positive and negative branches of a complete boolean match.
struct BoolArms<'hir> {
    /// Arm returning `true`.
    positive: &'hir Arm<'hir>,
    /// Arm returning `false`.
    negative: &'hir Arm<'hir>,
}

impl<'hir> BoolArms<'hir> {
    /// Finds the true and false arms of a boolean match.
    fn analyze(arms: &'hir [Arm<'hir>]) -> Option<Self> {
        Some(Self {
            positive: arms
                .iter()
                .find(|arm| is_bool_literal(arm.body) == Some(true))?,
            negative: arms
                .iter()
                .find(|arm| is_bool_literal(arm.body) == Some(false))?,
        })
    }
}

/// Resolves a direct unit-variant expression.
#[cfg(feature = "strum")]
fn unit_variant_expression(cx: &LateContext<'_>, expression: &Expr<'_>) -> Option<LocalDefId> {
    // A unit variant result must be a direct constructor path.
    let ExprKind::Path(path) = peel_transparent(expression).kind else {
        return None;
    };
    variant_from_res(cx, cx.qpath_res(&path, expression.hir_id))
}

/// Returns whether an expression is a direct path to a local binding.
fn is_local_path(cx: &LateContext<'_>, expression: &Expr<'_>, binding: rustc_hir::HirId) -> bool {
    let expression = peel_transparent(expression);

    // Only direct paths can be compared with the captured binding.
    let ExprKind::Path(path) = expression.kind else {
        return false;
    };
    matches!(cx.qpath_res(&path, expression.hir_id), Res::Local(found) if found == binding)
}

/// Checks that a `Some` payload returns every pattern binding in order.
#[cfg(feature = "strum")]
fn is_returning_bindings(
    cx: &LateContext<'_>,
    expression: &Expr<'_>,
    bindings: &[rustc_hir::HirId],
) -> bool {
    // A single binding is returned directly rather than wrapped in a tuple.
    if bindings.len() == 1 {
        return is_local_path(cx, expression, bindings[0]);
    }

    // Multiple bindings must be returned in their original tuple shape.
    let ExprKind::Tup(elements) = peel_transparent(expression).kind else {
        return false;
    };

    elements.len() == bindings.len()
        && elements
            .iter()
            .zip(bindings)
            .all(|(element, binding)| is_local_path(cx, element, *binding))
}

/// Variant identity and authored span recovered from a method body.
struct VariantMethodMatch {
    /// Variant handled by the method.
    variant: LocalDefId,
    /// Authored match expression.
    span: Span,
}

impl VariantMethodMatch {
    /// Exact arm count for a complete `Option` accessor match.
    #[cfg(feature = "strum")]
    const OPTION_MATCH_ARM_COUNT: usize = 2;

    /// Resolves an exact two-arm variant predicate.
    fn predicate(
        cx: &LateContext<'_>,
        expression: &Expr<'_>,
        receiver: rustc_hir::HirId,
    ) -> Option<Self> {
        let expression = peel_transparent(expression);

        // Predicate recognition starts with an explicit match expression.
        let ExprKind::Match(scrutinee, arms, _) = expression.kind else {
            return None;
        };

        // The match must cover only the receiver with exactly two outcomes.
        if !is_local_path(cx, scrutinee, receiver) || arms.len() != BOOLEAN_MATCH_ARM_COUNT {
            return None;
        }

        let BoolArms { positive, negative } = BoolArms::analyze(arms)?;

        // Guards or a non-wildcard fallback prevent a complete generated predicate.
        if positive.guard.is_some()
            || negative.guard.is_some()
            || !matches!(negative.pat.kind, PatKind::Wild)
        {
            return None;
        }

        let variant = ignored_variant_pattern(cx, positive.pat)?;
        Some(Self {
            variant,
            span: expression.span.source_callsite(),
        })
    }

    /// Resolves an exact two-arm payload extraction match.
    #[cfg(feature = "strum")]
    fn accessor(
        cx: &LateContext<'_>,
        expression: &Expr<'_>,
        receiver: rustc_hir::HirId,
    ) -> Option<Self> {
        let expression = peel_transparent(expression);

        // Accessor recognition starts with an explicit match expression.
        let ExprKind::Match(scrutinee, arms, _) = expression.kind else {
            return None;
        };

        // The match must cover only the receiver with `Some` and fallback arms.
        if !is_local_path(cx, scrutinee, receiver) || arms.len() != Self::OPTION_MATCH_ARM_COUNT {
            return None;
        }

        let success = arms
            .iter()
            .find(|arm| option_some(cx, arm.body).is_some())?;
        let failure = arms.iter().find(|arm| is_option_none(cx, arm.body))?;

        // Guards or a non-wildcard fallback prevent a complete generated accessor.
        if success.guard.is_some()
            || failure.guard.is_some()
            || !matches!(failure.pat.kind, PatKind::Wild)
        {
            return None;
        }
        let BoundTupleVariant { variant, bindings } = BoundTupleVariant::analyze(cx, success.pat)?;
        let returned = option_some(cx, success.body)?;

        // The success arm must return the original payload without transformation.
        if !is_returning_bindings(cx, returned, &bindings) {
            return None;
        }
        Some(Self {
            variant,
            span: expression.span.source_callsite(),
        })
    }
}

