/// One exact owned, shared, or mutable tuple-variant accessor.
#[cfg(feature = "strum")]
struct AccessorMethod {
    /// Authored declaration or expression range used as the diagnostic anchor.
    span: Span,
    /// Declaration whose lint level governs this finding.
    owner: rustc_hir::HirId,
    /// Local enum definition that owns the analyzed contract.
    enum_def: LocalDefId,
    /// Variant identity involved in the finding.
    variant: LocalDefId,
    /// Owned or borrowed receiver form implemented by this accessor.
    mode: AccessorMode,
    /// Whether replacement would change a public API.
    is_public_api: bool,
}

#[cfg(feature = "strum")]
impl AccessorMethod {
    /// Resolves one `Option` accessor that returns bound fields without transformation.
    fn from_impl_item(cx: &LateContext<'_>, item: &ImplItem<'_>) -> Option<Self> {
        // Generated methods cannot be identified reliably inside macro expansions.
        if item.span.from_expansion() {
            return None;
        }

        // Only function implementation items can supply an accessor body.
        let ImplItemKind::Fn(signature, body_id) = item.kind else {
            return None;
        };

        // Generated accessors must retain Strum's public, simple method contract.
        if signature.decl.inputs.len() != 1
            || signature.header.is_unsafe()
            || signature.header.is_async()
            || !cx
                .tcx
                .generics_of(item.owner_id.def_id)
                .own_params
                .is_empty()
            || !cx.tcx.visibility(item.owner_id.def_id).is_public()
            || cx
                .tcx
                .hir_attrs(item.hir_id())
                .iter()
                .any(|attribute| attribute.doc_str().is_some())
        {
            return None;
        }

        // Resolve the enum receiver and verify that the accessor returns an Option.
        let enum_def = enclosing_inherent_enum(cx, item.hir_id())?;
        let mode = AccessorMode::receiver_mode(cx, item.owner_id.def_id, enum_def)?;
        option_output(cx, item.owner_id.def_id)?;
        let body = cx.tcx.hir_body(body_id);

        let receiver = binding_id(body.params.first()?.pat)?;
        let VariantMethodMatch { variant, span } =
            VariantMethodMatch::accessor(cx, body.value, receiver)?;

        // The matched variant must belong to the enclosing enum.
        if owning_enum(cx, variant) != Some(enum_def) {
            return None;
        }

        let suffix = match mode {
            AccessorMode::Owned => "",
            AccessorMode::Shared => "_ref",
            AccessorMode::Mutable => "_mut",
        };

        let expected_name = format!(
            "try_as_{}{}",
            cx.tcx
                .item_name(variant.to_def_id())
                .as_str()
                .to_case(Case::Snake),
            suffix
        );

        // The method name must match the generated accessor naming scheme.
        if item.ident.name.as_str() != expected_name {
            return None;
        }

        Some(Self {
            span,
            owner: item.hir_id(),
            enum_def,
            variant,
            mode,
            is_public_api: cx.tcx.visibility(item.owner_id.def_id).is_public(),
        })
    }
}

/// Accumulates exact payload accessors until every generated method is represented.
#[cfg(feature = "strum")]
#[derive(Default)]
pub struct AccessorFamilyAnalyzer {
    /// Methods whose bodies establish the finding.
    methods: HashMap<LocalDefId, Vec<AccessorMethod>>,
}

#[cfg(feature = "strum")]
impl AccessorFamilyAnalyzer {
    /// Records one exact authored tuple-variant accessor when eligible.
    pub(crate) fn check_impl_item(&mut self, cx: &LateContext<'_>, item: &ImplItem<'_>) {
        // Only complete accessors contribute evidence to a family.
        let Some(method) = AccessorMethod::from_impl_item(cx, item) else {
            return;
        };
        self.methods
            .entry(method.enum_def)
            .or_default()
            .push(method);
    }

    /// Returns only families matching all three generated modes for every tuple variant.
    pub(crate) fn complete_families(&self, cx: &LateContext<'_>) -> Vec<AccessorFamily> {
        let mut families = self
            .methods
            .iter()
            .filter_map(|(&enum_def, methods)| {
                let variants = eligible_tuple_variants(cx, enum_def)?;
                let expected = variants.len().checked_mul(ACCESSOR_MODES_PER_VARIANT)?;
                let found = methods
                    .iter()
                    .map(|method| (method.variant, method.mode))
                    .collect::<HashSet<_>>();

                // A replacement is sound only when every variant has every accessor mode.
                if methods.len() != expected
                    || found.len() != expected
                    || !variants.iter().all(|variant| {
                        [
                            AccessorMode::Owned,
                            AccessorMode::Shared,
                            AccessorMode::Mutable,
                        ]
                        .into_iter()
                        .all(|mode| found.contains(&(*variant, mode)))
                    })
                {
                    return None;
                }
                let first = methods.first()?;
                Some(AccessorFamily {
                    span: first.span,
                    owner: first.owner,
                    enum_def,
                    is_public_api: methods.iter().any(|method| method.is_public_api),
                })
            })
            .collect::<Vec<_>>();
        families.sort_by_key(|family| family.span.lo());
        families
    }
}
